//! Independent QA test suite (black-box, written from the specification and frozen contracts).
//!
//! This library is intentionally empty; all tests are integration tests in `tests/`.
//!
//! # Independence
//! The tests are derived from `Cloud_System_Workspace_Platform_Specification.md` (v2.4.1),
//! `docs/SPEC_ERRATA.md` and `docs/contracts/M0-foundations.md`, not from the implementation.
//! Every call into engineer-owned code goes through ONE adapter file,
//! `tests/support/contract.rs`, so that when the implementation lands only that file needs
//! binding to the real function signatures. Test logic and expected values are never changed to
//! match an implementation; a disagreement is a finding for the Team Leader.
//!
//! # Features
//! * default: nothing compiles in `tests/` (every test file is `cfg`-gated), so
//!   `cargo build`/`cargo test --workspace` pass before the M0 crates are merged.
//! * `m0-contract`: binds the suite to the real M0 crates and the `cs` binary.
//! * `qa-selfcheck`: compiles the suite against a stub adapter (type-checks the QA code
//!   itself); tests needing the implementation panic with "QA stub".
//!
//! # Running (after M0 merge)
//! ```text
//! docker compose -f dev/docker-compose.yml up -d
//! cargo build -p cs                       # the HTTP tests spawn target/debug/cs (or $CS_QA_BIN)
//! CS_REQUIRE_DB=1 CS_TEST_DATABASE_URL=postgres://yugabyte@localhost:5433/yugabyte \
//!   cargo test -p cs-qa-tests --features m0-contract -- --test-threads=4
//! ```
//! Without `CS_REQUIRE_DB=1`, DB tests print `SKIP` and pass when no database is reachable.
//! With it, an unreachable database fails the run (after waiting up to `CS_QA_DB_WAIT_SECS`,
//! default 90 s, for YugabyteDB to finish starting).
//!
//! Every DB test creates its own uniquely named databases (`qa_<area>_<random>`) and drops
//! them afterwards, so tests may run in parallel and leave nothing behind.
//!
//! # Vectors
//! `vectors/signing_envelope.json` is generated by `vectors/gen/gen_sig_vectors.py`
//! (Python standard library only; an independent RFC 8032 Ed25519 and RFC 8949 CBOR
//! implementation, self-tested against RFC 8032 §7.1 and cross-checked against OpenSSL).
//! Regenerate with `python3 -I vectors/gen/gen_sig_vectors.py vectors/signing_envelope.json`;
//! the output is deterministic.
